import serial

PORT = "COM7"
BAUD_RATE = 115200

def main():
    try:
        with serial.Serial(
            port=PORT,
            baudrate=BAUD_RATE,
            bytesize=serial.EIGHTBITS,
            parity=serial.PARITY_NONE,
            stopbits=serial.STOPBITS_ONE,
            timeout=1,
        ) as ser:
            print(f"Listening on {PORT} at {BAUD_RATE} baud (8N1). Press Ctrl+C to stop.")
            while True:
                data = ser.read(1)
                if data:
                    value = data[0]
                    print(f"Received: 0x{value:02X}  (binary: {value:08b})")

    except serial.SerialException as exc:
        print(f"Serial error: {exc}")
        print("Check that the device is connected, COM7 is correct, and no other program is using the port.")
    except KeyboardInterrupt:
        print("\\\\nStopped.")

if __name__ == "__main__":
    main()